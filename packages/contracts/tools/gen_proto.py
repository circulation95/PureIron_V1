"""collector.proto → Python 생성물(.py + mypy-protobuf .pyi)을 서비스 `_gen/`에 쓴다.

생성기는 uv.lock으로 고정된 grpcio-tools(protoc 내장) + mypy-protobuf이고, 네트워크 없이 같은
입력에서 같은 바이트를 낸다. `buf`는 lint·breaking 전용이다(packages/contracts/README.md).

protoc는 `import collector_pb2`처럼 최상위 import를 생성하므로, 패키지 안 `_gen/`에서 동작하도록
상대 import(`from . import collector_pb2`)로 고쳐 쓴다.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CONTRACTS = ROOT / "packages" / "contracts"
PROTO_FILES = ("collector.proto",)
TARGETS = (
    ROOT / "services" / "core" / "src" / "pureiron_core" / "_gen",
    ROOT / "services" / "collector" / "src" / "pureiron_collector" / "_gen",
)
HEADER = "# Generated by packages/contracts/tools/gen_proto.py — DO NOT EDIT.\n"
_TOP_LEVEL_PB2_IMPORT = re.compile(r"^import (\w+_pb2)( as \w+)?$", re.MULTILINE)


def _plugin(name: str) -> str:
    found = shutil.which(name)
    if found is None:
        raise SystemExit(f"gen_proto: {name} not found on PATH (run via `uv run`)")
    return found


def _generate(out: Path) -> None:
    cmd = [
        sys.executable,
        "-m",
        "grpc_tools.protoc",
        f"-I{CONTRACTS}",
        f"--plugin=protoc-gen-mypy={_plugin('protoc-gen-mypy')}",
        f"--plugin=protoc-gen-mypy_grpc={_plugin('protoc-gen-mypy_grpc')}",
        f"--python_out={out}",
        f"--grpc_python_out={out}",
        f"--mypy_out={out}",
        f"--mypy_grpc_out={out}",
        *PROTO_FILES,
    ]
    subprocess.run(cmd, check=True, cwd=CONTRACTS)


def _rewrite(text: str) -> str:
    text = _TOP_LEVEL_PB2_IMPORT.sub(lambda m: f"from . import {m[1]}{m[2] or ''}", text)
    return HEADER + text.replace("\r\n", "\n")


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp)
        _generate(out)
        files = {p.name: _rewrite(p.read_text(encoding="utf-8")) for p in sorted(out.iterdir())}
    files["__init__.py"] = HEADER
    for target in TARGETS:
        if target.exists():
            shutil.rmtree(target)
        target.mkdir(parents=True)
        for name, text in files.items():
            (target / name).write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
